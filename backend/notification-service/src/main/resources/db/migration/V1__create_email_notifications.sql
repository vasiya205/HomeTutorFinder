-- Notification service schema (database: hometutor_notification). Managed by Flyway.
CREATE TABLE IF NOT EXISTS email_notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(40)  NOT NULL,
    recipient_email VARCHAR(160) NOT NULL,
    recipient_name  VARCHAR(120),
    subject         VARCHAR(200) NOT NULL,
    html_body       TEXT         NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'QUEUED'
                    CONSTRAINT email_status_check CHECK (status IN ('QUEUED', 'SENT', 'LOGGED', 'FAILED')),
    error_message   VARCHAR(500),
    sent_at         TIMESTAMP WITHOUT TIME ZONE,
    created_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_email_notifications_recipient ON email_notifications (LOWER(recipient_email));
CREATE INDEX IF NOT EXISTS ix_email_notifications_created   ON email_notifications (created_at DESC);
