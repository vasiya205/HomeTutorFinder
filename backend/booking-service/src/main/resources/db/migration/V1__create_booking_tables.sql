-- Booking service schema (database: hometutor_booking). Managed by Flyway.
CREATE TABLE IF NOT EXISTS bookings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id  BIGINT        NOT NULL,
    student_name     VARCHAR(120)  NOT NULL,
    student_email    VARCHAR(160)  NOT NULL,
    tutor_user_id    BIGINT        NOT NULL,
    tutor_name       VARCHAR(120)  NOT NULL,
    tutor_email      VARCHAR(160)  NOT NULL,
    subject          VARCHAR(80)   NOT NULL,
    start_date_time  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date_time    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    notes            TEXT          NOT NULL DEFAULT '',
    hourly_rate      NUMERIC(10, 2) NOT NULL CONSTRAINT bookings_rate_check CHECK (hourly_rate >= 0),
    total_amount     NUMERIC(10, 2) NOT NULL CONSTRAINT bookings_amount_check CHECK (total_amount >= 0),
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING'
                     CONSTRAINT bookings_status_check
                     CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'COMPLETED', 'CANCELLED')),
    payment_status   VARCHAR(20)   NOT NULL DEFAULT 'UNPAID'
                     CONSTRAINT bookings_payment_status_check CHECK (payment_status IN ('UNPAID', 'PENDING', 'PAID')),
    payment_mode     VARCHAR(20)
                     CONSTRAINT bookings_payment_mode_check CHECK (payment_mode IN ('RAZORPAY', 'DEMO')),
    payment_order_id VARCHAR(100),
    payment_id       VARCHAR(100),
    paid_at          TIMESTAMP WITHOUT TIME ZONE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT bookings_time_check CHECK (end_date_time > start_date_time)
);

CREATE INDEX IF NOT EXISTS ix_bookings_student ON bookings (student_user_id);
CREATE INDEX IF NOT EXISTS ix_bookings_tutor   ON bookings (tutor_user_id);
CREATE INDEX IF NOT EXISTS ix_bookings_time    ON bookings (start_date_time, end_date_time);
CREATE UNIQUE INDEX IF NOT EXISTS ux_bookings_payment_order ON bookings (payment_order_id) WHERE payment_order_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_bookings_payment_id    ON bookings (payment_id)       WHERE payment_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT       NOT NULL UNIQUE REFERENCES bookings (id) ON DELETE RESTRICT,
    student_user_id BIGINT       NOT NULL,
    student_name    VARCHAR(120) NOT NULL,
    tutor_user_id   BIGINT       NOT NULL,
    rating          INTEGER      NOT NULL CONSTRAINT reviews_rating_check CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT         NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_reviews_tutor ON reviews (tutor_user_id);
