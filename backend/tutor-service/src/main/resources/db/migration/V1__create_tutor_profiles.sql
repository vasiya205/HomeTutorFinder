-- Tutor service schema (database: hometutor_tutor). Managed by Flyway.
CREATE TABLE IF NOT EXISTS tutor_profiles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL UNIQUE,
    full_name        VARCHAR(120)  NOT NULL,
    email            VARCHAR(160)  NOT NULL,
    qualification    VARCHAR(150)  NOT NULL,
    subject          VARCHAR(80)   NOT NULL,
    location         VARCHAR(80)   NOT NULL,
    experience_years INTEGER       NOT NULL CONSTRAINT tutor_experience_check CHECK (experience_years BETWEEN 0 AND 60),
    bio              TEXT          NOT NULL,
    hourly_rate      NUMERIC(10, 2) NOT NULL CONSTRAINT tutor_rate_check CHECK (hourly_rate >= 0),
    teaching_mode    VARCHAR(10)   NOT NULL DEFAULT 'BOTH'
                     CONSTRAINT tutor_mode_check CHECK (teaching_mode IN ('HOME', 'ONLINE', 'BOTH')),
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_tutor_profiles_subject  ON tutor_profiles (LOWER(subject));
CREATE INDEX IF NOT EXISTS ix_tutor_profiles_location ON tutor_profiles (LOWER(location));
CREATE INDEX IF NOT EXISTS ix_tutor_profiles_rate     ON tutor_profiles (hourly_rate);
