export function resourcesForSubject(subject = '') {
  const needle = subject.trim().toLowerCase()
  if (!needle) return []
  return studyResources.filter((resource) =>
    resource.subject.toLowerCase() === needle
    || resource.keywords.some((keyword) => keyword.includes(needle) || needle.includes(keyword)))
}
